import streamlit as st

# تعريف عنوان الصفحة
st.set_page_config(page_title="نظام التنبؤ بالكنز")

# 1. العنوان الرئيسي والسيناريو
st.title("نظام التنبؤ بالكنز: مشروع الذكاء الاصطناعي")
st.markdown("---")
st.markdown("""
**السيناريو:** يمثل هذا التطبيق نموذجاً مبسطاً لنظام دعم قرار (الذكاء الاصطناعي) يقوم بتقييم **احتمالية العثور على كنز** بناءً على ثلاث مدخلات أساسية.
""")

# 2. المدخلات التفاعلية (المؤشرات)

st.subheader("تحكم في المدخلات لتغيير نسبة التنبؤ:")

# مؤشر الوثائق (الوزن: 40%)
وثائق_تاريخية = st.slider(
    '1. احتمال توفر الوثائق والخرائط التاريخية (وزن 40%):',
    min_value=0.0, max_value=1.0, value=0.5, step=0.05
)

# مؤشر المسح (الوزن: 35%)
دقة_المسح = st.slider(
    '2. دقة المسح الجيوفيزيائي للمنطقة (وزن 35%):',
    min_value=0.0, max_value=1.0, value=0.5, step=0.05
)

# مؤشر الإشارات (الوزن: 25%)
نسبة_الإشارات = st.slider(
    '3. نسبة وجود الإشارات الجغرافية غير الطبيعية (وزن 25%):',
    min_value=0.0, max_value=1.0, value=0.5, step=0.05
)

# 3. الحساب والنتيجة النهائية
# المعادلة: (0.4 * الوثائق) + (0.35 * المسح) + (0.25 * الإشارات)
احتمال_الكنز_اللاحق = (0.40 * وثائق_تاريخية) + (0.35 * دقة_المسح) + (0.25 * نسبة_الإشارات)
النتيجة_المئوية = احتمال_الكنز_اللاحق * 100

st.markdown("---")
st.subheader("النتيجة (الاحتمال اللاحق):")

# عرض النتيجة بشكل كبير ومميز (كما في الدائرة المئوية في مثال الدكتورة)
col1, col2 = st.columns([1, 2])
with col1:
    # القيمة المئوية
    st.metric(label="احتمال العثور على الكنز", value=f"{النتيجة_المئوية:.1f}%")

with col2:
    # تحليل النص بناءً على النتيجة
    if النتيجة_المئوية >= 70:
        st.success("تنبؤ مرتفع جداً: جميع المدخلات تدعم فرضية وجود الكنز. يُنصح بالبدء في التنقيب.")
    elif النتيجة_المئوية >= 40:
        st.warning("تنبؤ متوسط: هناك حاجة للمزيد من البيانات والتحليل لرفع الاحتمال.")
    else:
        st.error("تنبؤ منخفض: لا يوجد دليل قوي، يرجى إعادة التقييم أو تغيير الموقع.")

st.caption("هذا المشروع تم تطويره باستخدام مكتبة Streamlit، وهي أداة سريعة لإنشاء تطبيقات ويب تفاعلية.")